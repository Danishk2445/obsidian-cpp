#!/usr/bin/env python3
"""Generate the static tables used by the inline Markdown parser (src/markdown/*.inc).

    tools/gen_markdown_tables.py entities > src/markdown/html_entities_table.inc
    tools/gen_markdown_tables.py casefold > src/markdown/case_fold_table.inc

entities: the WHATWG HTML5 named character references (Python's html.entities.html5, a copy of
          https://html.spec.whatwg.org/entities.json). Only names terminated by ';' are emitted:
          CommonMark entity references always require the semicolon.
casefold: code points whose Unicode *full* case folding expands to several code points (e.g. U+1E9E
          -> "ss"). Qt's QString::toCaseFolded() implements simple folding only; link labels need full
          folding (CommonMark "[ẞ]" matches a definition "[SS]").
"""
import html.entities
import sys


def entities():
    rows = []
    for name, value in html.entities.html5.items():
        if not name.endswith(';'):
            continue
        cps = [ord(c) for c in value]
        assert 1 <= len(cps) <= 2, name
        rows.append((name[:-1], cps[0], cps[1] if len(cps) > 1 else 0))
    rows.sort(key=lambda r: r[0].encode('ascii'))
    print('// GENERATED by tools/gen_markdown_tables.py from the WHATWG HTML5 named character references.')
    print('// Do not edit. Sorted by name (ASCII order) for binary search; {name, codepoint1, codepoint2 or 0}.')
    for name, a, b in rows:
        print(f'{{"{name}", 0x{a:X}, 0x{b:X}}},')


def casefold():
    print(f'// GENERATED by tools/gen_markdown_tables.py (Python {sys.version.split()[0]} str.casefold()).')
    print('// Do not edit. Code points whose full case folding has several code points; sorted by code point.')
    print('// {codepoint, folded1, folded2, folded3 or 0}')
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        f = chr(cp).casefold()
        if len(f) > 1:
            cps = [ord(c) for c in f] + [0, 0]
            assert len(f) <= 3
            print(f'{{0x{cp:X}, 0x{cps[0]:X}, 0x{cps[1]:X}, 0x{cps[2]:X}}},')


if __name__ == '__main__':
    {'entities': entities, 'casefold': casefold}[sys.argv[1] if len(sys.argv) > 1 else 'entities']()
